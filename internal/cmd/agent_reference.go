// agentReferenceData holds the curated task text of the agent reference. The
// command paths, flags and examples it names are checked against the command
// tree, and everything else (usage lines, flag descriptions, the command index)
// comes from the tree itself.
//
//go:embed agent_reference.yaml
var agentReferenceData []byte

type agentReference struct {
	Title    string                `yaml:"title"`
	Intro    string                `yaml:"intro"`
	Basics   []agentReferenceBasic `yaml:"basics"`
	Sections []agentReferenceTask  `yaml:"sections"`
}

type agentReferenceBasic struct {
	Title string `yaml:"title"`
	Text  string `yaml:"text"`
}

type agentReferenceTask struct {
	Title    string                  `yaml:"title"`
	Intro    string                  `yaml:"intro"`
	Commands []agentReferenceCommand `yaml:"commands"`
}

type agentReferenceCommand struct {
	Path     string   `yaml:"path"`
	Flags    []string `yaml:"flags"`
	Examples []string `yaml:"examples"`
	Note     string   `yaml:"note"`
}

// refCommand is one command the reference documents: a cobra command, or an
// operation of a generated resource mounted as a single command, which parses
// its operation name itself.
type refCommand struct {
	path  string
	short string
	cobra *cobra.Command
	op    *cli.Command
}

// agentReferenceFlag is one documented flag of a command.
type agentReferenceFlag struct {
	name  string
	short string
	typ   string
	usage string
}

func newDocsCmd() *cobra.Command {
	docs := &cobra.Command{
		Use:    "docs",
		Short:  "Generate CLI documentation",
		Hidden: true,
	}
	docs.AddCommand(&cobra.Command{
		Use:         "agents",
		Short:       "Print the task-oriented CLI reference for coding agents as Markdown",
		Args:        cobra.NoArgs,
		Annotations: map[string]string{cmdutil.NoJSONOutputAnnotation: "true"},
		RunE: func(cmd *cobra.Command, _ []string) error {
			return writeAgentReference(cmd.OutOrStdout(), cmd.Root())
		},
	})
	return docs
}

// writeAgentReference renders the agent reference for root. It fails when the
// curated data names a command, flag or example the tree doesn't have.
func writeAgentReference(w io.Writer, root *cobra.Command) error {
	var ref agentReference
	if err := yaml.UnmarshalWithOptions(agentReferenceData, &ref, yaml.Strict()); err != nil {
		return fmt.Errorf("agent_reference.yaml: %w", err)
	}
	var errs []error
	var b strings.Builder

	fmt.Fprintf(&b, "# %s\n\n", ref.Title)
	b.WriteString("<!-- Generated by `langsmith docs agents` from the command tree and internal/cmd/agent_reference.yaml. Do not edit; run `make agent-docs`. -->\n\n")
	b.WriteString(strings.TrimSpace(ref.Intro) + "\n\n")

	b.WriteString("## Basics\n\n")
	b.WriteString("### Global flags\n\n")
	b.WriteString("| Flag | Description |\n|---|---|\n")
	root.PersistentFlags().VisitAll(func(f *pflag.Flag) {
		if f.Hidden {
			return
		}
		writeFlagRow(&b, cobraFlag(f))
	})
	b.WriteString("\n")
	for _, basic := range ref.Basics {
		text := strings.ReplaceAll(strings.TrimSpace(basic.Text), cursorCommandsPlaceholder, codeList(cursorCommands(root)))
		fmt.Fprintf(&b, "### %s\n\n%s\n\n", basic.Title, text)
		errs = append(errs, checkInlineCommands(root, basic.Title, basic.Text)...)
	}

	for _, section := range ref.Sections {
		fmt.Fprintf(&b, "## %s\n\n", section.Title)
		if intro := strings.TrimSpace(section.Intro); intro != "" {
			b.WriteString(intro + "\n\n")
			errs = append(errs, checkInlineCommands(root, section.Title, intro)...)
		}
		for _, entry := range section.Commands {
			errs = append(errs, writeTaskCommand(&b, root, entry)...)
		}
	}

	b.WriteString("## All commands\n\n")
	b.WriteString("Every command in this version of the CLI. Run `langsmith <command> --help` for its flags. Commands marked *confirms* ask before deleting; see [Safety](#safety).\n\n")
	b.WriteString("| Command | Description |\n|---|---|\n")
	for _, c := range leafCommands(root) {
		desc := summary(c.short)
		if confirmsDelete(c) {
			desc += " *(confirms)*"
		}
		fmt.Fprintf(&b, "| `%s` | %s |\n", c.path, escapeCell(desc))
	}

	if err := errors.Join(errs...); err != nil {
		return err
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func writeTaskCommand(b *strings.Builder, root *cobra.Command, entry agentReferenceCommand) []error {
	c, ok := findCommand(root, "langsmith "+entry.Path)
	if !ok {
		return []error{fmt.Errorf("agent reference: no command %q", entry.Path)}
	}
	var errs []error
	flags := commandFlags(c)
	fmt.Fprintf(b, "### `%s`\n\n", c.path)
	fmt.Fprintf(b, "%s\n\n", summary(c.short))
	if c.cobra.Annotations[generatedAnnotation] == "" {
		fmt.Fprintf(b, "Usage: `%s`\n\n", c.cobra.UseLine())
	}
	if len(entry.Flags) > 0 {
		b.WriteString("| Flag | Description |\n|---|---|\n")
		for _, name := range entry.Flags {
			f, ok := lookupFlag(flags, name)
			if !ok {
				errs = append(errs, fmt.Errorf("agent reference: %s has no flag %s", c.path, name))
				continue
			}
			writeFlagRow(b, f)
		}
		b.WriteString("\n")
	}
	if note := strings.TrimSpace(entry.Note); note != "" {
		b.WriteString(note + "\n\n")
		errs = append(errs, checkInlineCommands(root, c.path, note)...)
	}
	if len(entry.Examples) > 0 {
		b.WriteString("```bash\n")
		for _, ex := range entry.Examples {
			if err := checkExample(root, ex); err != nil {
				errs = append(errs, err)
			}
			b.WriteString(ex + "\n")
		}
		b.WriteString("```\n\n")
	}
	return errs
}

// inlineCommand matches a `langsmith ...` command written in backticks.
var inlineCommand = regexp.MustCompile("`(langsmith [^`]+)`")

// checkInlineCommands checks every backticked langsmith command in text.
func checkInlineCommands(root *cobra.Command, where, text string) []error {
	var errs []error
	for _, m := range inlineCommand.FindAllStringSubmatch(text, -1) {
		if strings.Contains(m[1], "<command>") {
			continue
		}
		if err := checkExample(root, m[1]); err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", where, err))
		}
	}
	return errs
}

// checkExample checks that ex runs an existing command with flags it accepts.
// Arguments are split on spaces and quotes are not interpreted, so quoted
// values must not contain words starting with "-".
func checkExample(root *cobra.Command, ex string) error {
	words := strings.Fields(ex)
	var c refCommand
	var found bool
	i := len(words)
	for ; i > 1; i-- {
		if c, found = findCommand(root, strings.Join(words[:i], " ")); found {
			break
		}
	}
	if !found {
		return fmt.Errorf("agent reference: example %q does not name a command", ex)
	}
	flags := commandFlags(c)
	for _, w := range words[i:] {
		if !strings.HasPrefix(w, "-") || w == "-" {
			continue
		}
		name, _, _ := strings.Cut(w, "=")
		if _, ok := lookupFlag(flags, name); !ok {
			return fmt.Errorf("agent reference: example %q: %s has no flag %s", ex, c.path, name)
		}
	}
	return nil
}

// commandFlags returns the documented flags of c, including global ones.
// Generated commands parse their own flags, so theirs come from the
// generated operation.
func commandFlags(c refCommand) []agentReferenceFlag {
	var flags []agentReferenceFlag
	if c.op != nil {
		for _, f := range c.op.Flags {
			flags = append(flags, urfaveFlag(f))
		}
	} else {
		c.cobra.Flags().VisitAll(func(f *pflag.Flag) {
			if !f.Hidden {
				flags = append(flags, cobraFlag(f))
			}
		})
	}
	c.cobra.InheritedFlags().VisitAll(func(f *pflag.Flag) {
		if !f.Hidden {
			flags = append(flags, cobraFlag(f))
		}
	})
	// Generated deletes accept --yes, which langsmith handles before the
	// generated tree parses the rest.
	if c.op != nil && isDeleteOperation(c.op.Name) {
		flags = append(flags, agentReferenceFlag{name: "yes", usage: "Skip the confirmation prompt"})
	}
	return flags
}

// generatedResource returns the generated resource c runs, or nil for a
// hand-written command.
func generatedResource(c *cobra.Command) *cli.Command {
	for _, r := range generated.Command.Commands {
		if name := c.Annotations[generatedAnnotation]; name != "" && r.Name == name {
			return r
		}
	}
	return nil
}

// generatedOperation returns the operation of resource named name.
func generatedOperation(resource *cli.Command, name string) *cli.Command {
	for _, op := range resource.Commands {
		if op.Name == name {
			return op
		}
	}
	return nil
}

func cobraFlag(f *pflag.Flag) agentReferenceFlag {
	typ := f.Value.Type()
	if typ == "bool" {
		typ = ""
	}
	return agentReferenceFlag{name: f.Name, short: f.Shorthand, typ: typ, usage: f.Usage}
}

func urfaveFlag(f cli.Flag) agentReferenceFlag {
	names := f.Names()
	flag := agentReferenceFlag{name: names[0]}
	for _, n := range names[1:] {
		if len(n) == 1 {
			flag.short = n
		}
	}
	if d, ok := f.(cli.DocGenerationFlag); ok {
		flag.usage = d.GetUsage()
		if d.TakesValue() {
			flag.typ = d.TypeName()
		}
	}
	return flag
}

func lookupFlag(flags []agentReferenceFlag, name string) (agentReferenceFlag, bool) {
	for _, f := range flags {
		if "--"+f.name == name || (f.short != "" && "-"+f.short == name) {
			return f, true
		}
	}
	return agentReferenceFlag{}, false
}

func writeFlagRow(b *strings.Builder, f agentReferenceFlag) {
	spelling := "--" + f.name
	if f.short != "" {
		spelling = "-" + f.short + ", " + spelling
	}
	if f.typ != "" {
		spelling += " " + f.typ
	}
	usage := f.usage
	if usage == "" {
		usage = "—"
	}
	fmt.Fprintf(b, "| `%s` | %s |\n", spelling, escapeCell(usage))
}

// findCommand returns the documented command with the given full path.
func findCommand(root *cobra.Command, path string) (refCommand, bool) {
	for _, c := range leafCommands(root) {
		if c.path == path {
			return c, true
		}
	}
	return refCommand{}, false
}

// leafCommands returns every visible command that runs something, in path
// order. A generated resource mounted as one command contributes one entry
// per operation.
func leafCommands(root *cobra.Command) []refCommand {
	var leaves []refCommand
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		var visible int
		for _, sub := range c.Commands() {
			if sub.Hidden || sub.Name() == "help" || sub.Name() == "completion" {
				continue
			}
			visible++
			walk(sub)
		}
		// A parent runs something itself only when it takes arguments, like
		// `langsmith api PATH`; the others just print help.
		if c == root || !c.Runnable() || (visible > 0 && c.ValidateArgs([]string{"arg"}) != nil) {
			return
		}
		resource := generatedResource(c)
		switch {
		case resource == nil:
			leaves = append(leaves, refCommand{path: c.CommandPath(), short: c.Short, cobra: c})
		case generatedOperation(resource, c.Name()) != nil && c.Name() != resource.Name:
			leaves = append(leaves, refCommand{path: c.CommandPath(), short: c.Short, cobra: c, op: generatedOperation(resource, c.Name())})
		default:
			for _, op := range resource.Commands {
				if !op.Hidden {
					leaves = append(leaves, refCommand{path: c.CommandPath() + " " + op.Name, short: op.Usage, cobra: c, op: op})
				}
			}
		}
	}
	walk(root)
	slices.SortFunc(leaves, func(a, b refCommand) int { return strings.Compare(a.path, b.path) })
	return leaves
}

// cursorCommandsPlaceholder in the curated text is replaced by the list of
// cursorCommands.
const cursorCommandsPlaceholder = "{cursor_commands}"

// cursorCommands returns the paths of hand-written commands that accept
// --cursor and report cursors.next. Generated commands pass their cursor
// through to the API, whose response shape varies.
func cursorCommands(root *cobra.Command) []string {
	var paths []string
	for _, c := range leafCommands(root) {
		if c.cobra.Annotations[generatedAnnotation] != "" {
			continue
		}
		if _, ok := lookupFlag(commandFlags(c), "--cursor"); ok {
			paths = append(paths, c.path)
		}
	}
	return paths
}

// confirmsDelete reports whether c is a delete that asks for confirmation and
// takes --yes to skip it. Every generated delete does; a hand-written one does
// when it defines --yes.
func confirmsDelete(c refCommand) bool {
	if c.op != nil {
		return isDeleteOperation(c.op.Name)
	}
	return isDeleteOperation(c.cobra.Name()) && c.cobra.LocalFlags().Lookup("yes") != nil
}

// maturityNote matches the note that opens a beta or alpha endpoint's
// description.
var maturityNote = regexp.MustCompile(`^\*\*(\w+):\*\* This endpoint is in active development and may change without notice\.`)

// summary returns the first sentence of a short description. Generated
// descriptions repeat the OpenAPI summary, which can span lines.
func summary(short string) string {
	s := strings.Join(strings.Fields(short), " ")
	// Several generated descriptions open with a note on the HTTP method or
	// the endpoint's maturity.
	s = strings.TrimPrefix(s, "GET with body payload — no resources created. ")
	if m := maturityNote.FindStringSubmatch(s); m != nil {
		rest := strings.TrimSpace(s[len(m[0]):])
		if rest == "" {
			rest = "may change without notice."
		}
		s = m[1] + ": " + rest
	}
	if i := strings.Index(s, ". "); i >= 0 {
		s = s[:i+1]
	}
	return s
}

func codeList(items []string) string {
	quoted := make([]string, len(items))
	for i, s := range items {
		quoted[i] = "`" + s + "`"
	}
	return strings.Join(quoted, ", ")
}

func escapeCell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", `\|`)
}
