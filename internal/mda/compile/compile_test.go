func TestCompileInlinesTextModuleImports(t *testing.T) {
	f := typescriptProject(t, map[string]string{
		"prompt.md": "# Prompt\n\nUse `code` and ${vars}.\n",
		"agent.ts": tsImport +
			"import promptText from \"./prompt.md\" with { type: \"text\" };\n" +
			"export const agent = defineDeepAgent({ name: \"agent\", tools: [promptText] });\n",
	})

	mustCompile(t, f.deploy)

	want := tsImport +
		"const promptText = `# Prompt\n\nUse \\`code\\` and \\${vars}.\n`;\n" +
		"export const agent = defineDeepAgent({ name: \"agent\", tools: [promptText] });\n"
	if got := f.read(t, "agent.ts"); got != want {
		t.Fatalf("agent.ts: %q", got)
	}
	// The referenced markdown is still carried into the build verbatim.
	if !f.exists("prompt.md") {
		t.Fatal("prompt.md was not copied")
	}
}

func TestCompileReplacesPreviousBuildOutput(t *testing.T) {
	f := typescriptProject(t, map[string]string{"agent.ts": tsAgent})
	f.outDir = filepath.Join(f.root(), "build")
	// A stale artifact in a stamped build directory is removed by the next
	// compile.
	writeFile(t, f.outDir, buildMarker, "stamp")
	writeFile(t, f.outDir, "stale.txt", "old")
	// Dependency caches survive.
	writeFile(t, f.outDir, "node_modules/zod/index.js", "cached")

	mustCompile(t, f.deploy)

	if f.exists("stale.txt") || !f.exists("agent.ts") || !f.exists("_mda_entry.ts") {
		t.Fatal("the build was not replaced")
	}
	if got := f.read(t, buildMarker); got != buildMarkerContents {
		t.Fatalf("marker: %q", got)
	}
	if got := f.read(t, "node_modules/zod/index.js"); got != "cached" {
		t.Fatalf("node_modules was not kept: %q", got)
	}
}
