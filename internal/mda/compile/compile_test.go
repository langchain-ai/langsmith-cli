// End-to-end compilation (`compile/tests.rs`). Tests of reading authored
// source (names, unsupported keys, memory and identity shapes) are
// introspect's; these cover what compile builds from it.

func readJSON(t *testing.T, text string) map[string]any {
	t.Helper()
	var value map[string]any
	if err := json.Unmarshal([]byte(text), &value); err != nil {
		t.Fatalf("invalid JSON: %v\n%s", err, text)
	}
	return value
}

func TestCompileRejectsManagedSettingsBeforeReplacingBuildOutput(t *testing.T) {
	for _, tc := range []struct {
		name    string
		project func(*testing.T) fixture
		error   string
	}{
		{"typescript", func(t *testing.T) fixture {
			return typescriptProject(t, map[string]string{
				"agent.ts": tsImport + "export const agent = defineDeepAgent({ name: 'research', memory: null });\n",
			})
		}, "agent.ts: Remove `memory` from defineDeepAgent(...). Use a factory entrypoint to select memory per run; static agents use memory.ts."},
		{"python", func(t *testing.T) fixture {
			return pythonProject(t, map[string]string{
				"agent.py": pyImport + "agent = define_deep_agent(name='research', skills=None)\n",
			})
		}, "agent.py: Remove `skills` from define_deep_agent(...). Use a factory entrypoint to select skills per run; static agents use skills/."},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f := tc.project(t)
			writeFile(t, f.outDir, "previous.txt", "keep this build")
			writeFile(t, f.outDir, buildMarker, "")

			_, err := f.deploy(t)
			if err == nil || err.Error() != tc.error {
				t.Fatalf("got %v, want %q", err, tc.error)
			}
			if got := f.read(t, "previous.txt"); got != "keep this build" {
				t.Fatalf("previous build output changed: %q", got)
			}
		})
	}
}

func TestCompileCopiesFilesVerbatimAndGeneratesAManagedEntry(t *testing.T) {
	f := typescriptProject(t, map[string]string{
		"agent.ts":          tsAgent,
		"tools/query-db.ts": "export const queryDB = 1;\n",
	})

	mustCompile(t, f.deploy)

	// The user's agent file is carried over byte-for-byte: no transform.
	if got := f.read(t, "agent.ts"); got != tsAgent {
		t.Fatalf("agent.ts: %q", got)
	}
	// Other files are carried over byte-for-byte too.
	if got := f.read(t, "tools/query-db.ts"); got != "export const queryDB = 1;\n" {
		t.Fatalf("tools/query-db.ts: %q", got)
	}
	want := `// Generated by ` + "`mda deploy`" + ` — do not edit.
//
// Wraps the user's ` + "`defineDeepAgent(...)`" + ` definition into a managed LangGraph
// graph factory. The platform-owned backend (configured sandbox when declared,
// otherwise StateBackend scratch), store, checkpointer, and runtime context are
// injected by the managed runtime, not by the agent author.
import { compileManagedAgent } from "managed-deepagents/runtime";
import { assertStaticAgentDefinition } from "managed-deepagents/runtime";
import type { ManagedRunConfig, ManagedServerRuntime } from "managed-deepagents/runtime";
import { agent as definition } from "./agent";

const contextRepo = "context-repo";
const hasSkills = false;
const asyncSubagentGraphs = { "general-purpose": "agent--general-purpose" };

export function agent(config: ManagedRunConfig, runtime: ManagedServerRuntime) {
  assertStaticAgentDefinition(definition);
  return compileManagedAgent(definition, config, { contextRepo, hasSkills, asyncSubagentGraphs }, runtime);
}

export function agent__general_purpose(config: ManagedRunConfig, runtime: ManagedServerRuntime) {
  return compileManagedAgent(definition, config, { contextRepo, hasSkills, asyncSubagent: "general-purpose" }, runtime);
}
`
	if got := f.read(t, "_mda_entry.ts"); got != want {
		t.Fatalf("_mda_entry.ts:\n%s", got)
	}
	wantManifest := `{
  "node_version": "22",
  "_INTERNAL_docker_tag": "0.18.0.dev12-node22",
  "dependencies": [
    "."
  ],
  "graphs": {
    "agent": "./_mda_entry.ts:agent",
    "agent--general-purpose": "./_mda_entry.ts:agent__general_purpose"
  },
  "env": ".env"
}
`
	if got := f.read(t, "langgraph.json"); got != wantManifest {
		t.Fatalf("langgraph.json:\n%s", got)
	}
}

func TestCompileBuildsNamedFactoriesWithoutRunningThem(t *testing.T) {
	for _, tc := range []struct {
		name    string
		project func(*testing.T) fixture
		entry   string
	}{
		{"typescript", func(t *testing.T) fixture {
			return typescriptProject(t, map[string]string{
				"agent.ts": tsImport + "export const agent = defineAgent(\"plain\", async (runtime) => {\n" +
					"  throw new Error(\"the factory must not run\");\n});\n",
			})
		}, "_mda_entry.ts"},
		{"python", func(t *testing.T) fixture {
			return pythonProject(t, map[string]string{
				"agent.py": pyImport + "async def build(runtime):\n    raise RuntimeError('the factory must not run')\n" +
					"agent = define_agent('plain', build)\n",
			})
		}, "_mda_entry.py"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f := tc.project(t)
			mustCompile(t, f.deploy)
			graphs := readJSON(t, f.read(t, "langgraph.json"))["graphs"].(map[string]any)
			if graphs["plain"] != "./"+tc.entry+":agent" {
				t.Fatalf("graphs: %v", graphs)
			}
			entry := f.read(t, tc.entry)
			if tc.name == "python" {
				requireContains(t, entry, "compile_managed_agent_async(_definition, config,", "runtime=runtime)")
				requireNotContains(t, entry, "assert_static_agent_definition")
			} else {
				requireContains(t, entry, "compileManagedAgent(definition, config,", "}, runtime)")
				requireNotContains(t, entry, "assertStaticAgentDefinition")
			}
		})
	}
}

func TestCompileBuildsATypescriptFactoryEntryWithoutRunningTheFactory(t *testing.T) {
	f := typescriptProject(t, map[string]string{
		"agent.ts": tsImport + "export const agent = defineAgent(\"support\", () => {\n" +
			"  throw new Error(\"the factory must not run\");\n});\n",
		"package.json": "{\n  \"name\": \"dynamic-example\",\n  \"type\": \"module\",\n  \"dependencies\": {\n" +
			"    \"@langchain/openai\": \"1.5.5\",\n    \"@langchain/anthropic\": \"1.5.1\"\n  }\n}\n",
		"tools/mcp.ts": "import { defineMcp } from \"managed-deepagents\";\n" +
			"export const mcp = defineMcp({\n" +
			"  servers: { docs: { transport: \"http\", url: \"https://docs.example.com/mcp\" } },\n});\n",
		"memory.ts": "import { defineMemory, memoryLayer } from \"managed-deepagents\";\n" +
			"export const memory = defineMemory({ agent: memoryLayer() });\n",
		"skills/team-playbook/SKILL.md": "# Team playbook\n",
	})

	summary := mustCompile(t, f.deploy)

	if !reflect.DeepEqual(summary.Connectors, []string{filepath.Join("tools", "mcp.ts")}) {
		t.Fatalf("connectors: %v", summary.Connectors)
	}
	langgraph := readJSON(t, f.read(t, "langgraph.json"))
	want := map[string]any{
		"support":                  "./_mda_entry.ts:agent",
		"support--general-purpose": "./_mda_entry.ts:agent__general_purpose",
	}
	if !reflect.DeepEqual(langgraph["graphs"], want) {
		t.Fatalf("graphs: %v", langgraph["graphs"])
	}
	entry := f.read(t, "_mda_entry.ts")
	requireNotContains(t, entry, "assertStaticAgentDefinition")
	requireContains(t, entry, "import { connectors } from \"./_mda_connectors\";", "import { memory } from \"./memory\";")
	dependencies := readJSON(t, f.read(t, "package.json"))["dependencies"].(map[string]any)
	if dependencies["@langchain/openai"] != "1.5.5" || dependencies["@langchain/anthropic"] != "1.5.1" {
		t.Fatalf("dependencies: %v", dependencies)
	}
}

