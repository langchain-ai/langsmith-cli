func TestCompileSkipsTypescriptIngressChannelHelpers(t *testing.T) {
	f := typescriptProject(t, map[string]string{
		"agent.ts":          tsAgent,
		"identity.ts":       tsIdentity,
		"channels/slack.ts": tsSlack,
		"channels/slack.test.ts": "throw new Error(\n" +
			"  \"channels/slack.test.ts must not be imported at managed runtime startup\"\n);\n",
		"channels/helper.ts": "export const SHARED_ON = [\"app_mention\"] as const;\n",
	})

	summary := mustCompile(t, f.deploy)

	if !reflect.DeepEqual(summary.Channels, []string{filepath.Join("channels", "slack.ts")}) ||
		!reflect.DeepEqual(summary.ChannelProviders, []string{"slack"}) {
		t.Fatalf("channels: %v %v", summary.Channels, summary.ChannelProviders)
	}
	want := "// Generated by `mda deploy` — do not edit.\n//\n" +
		"// Collects and validates the channels discovered under `channels/`.\n" +
		"import { collectChannels } from \"managed-deepagents/runtime\";\n" +
		"import * as _channel0 from \"./channels/slack\";\n\n" +
		"export const channels = collectChannels([\n" +
		"  { source: \"channels/slack.ts\", module: _channel0 },\n]);\n"
	if got := f.read(t, "_mda_channels.ts"); got != want {
		t.Fatalf("_mda_channels.ts:\n%s", got)
	}
	if !f.exists("channels/slack.test.ts") || !f.exists("channels/helper.ts") {
		t.Fatal("the helpers were not copied")
	}
}

