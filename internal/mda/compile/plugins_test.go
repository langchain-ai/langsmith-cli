// Connectors, channels, identity, and the generated aggregators, auth module
// and managed HTTP app. Helpers and co-located tests under plugin directories
// must not be imported.

const (
	tsMcp = "import { defineMcp } from \"managed-deepagents\";\n" +
		"export const mcp = defineMcp({\n" +
		"  servers: { docs: { transport: \"http\", url: \"https://docs.example.com/mcp\" } },\n});\n"
	pyMcp = "from managed_deepagents import define_mcp\n" +
		"mcp = define_mcp(servers={\"docs\": {\"transport\": \"http\", \"url\": \"https://docs.example.com/mcp\"}})\n"
	tsSlack = "import { channels } from \"managed-deepagents\";\n" +
		"export const channel = channels.slack({ name: \"Support Bot\" });\n"
	pySlack = "from managed_deepagents import channels\nchannel = channels.slack(name=\"Support Bot\")\n"
)

// managedMcpAdapterVersion is the managed `@langchain/mcp-adapters` spec.
func managedMcpAdapterVersion(t *testing.T) string {
	t.Helper()
	for _, dep := range project.ManagedDependencies(project.TypeScript) {
		if dep.Name == "@langchain/mcp-adapters" {
			return dep.Version
		}
	}
	t.Fatal("the managed TypeScript stack does not carry the MCP adapter")
	return ""
}

func TestCompileWiresTypescriptToolsMcp(t *testing.T) {
	f := typescriptProject(t, map[string]string{
		"agent.ts":     tsAgent,
		"tools/mcp.ts": tsMcp,
		"package.json": "{\n  \"name\": \"example\",\n  \"type\": \"module\",\n  \"dependencies\": {}\n}\n",
	})

	mustCompile(t, f.deploy)

	// The entry imports the validated `connectors` list from the generated
	// aggregator and passes it in shorthand form to the managed runtime.
	requireContains(t, f.read(t, "_mda_entry.ts"), "import { connectors } from \"./_mda_connectors\";",
		"compileManagedAgent(definition, config, { contextRepo, hasSkills, connectors, asyncSubagentGraphs }, runtime)")
	// The aggregator imports each connector module name-agnostically and
	// validates the connector brand via `collectConnectors`.
	want := "// Generated by `mda deploy` — do not edit.\n//\n" +
		"// Collects and validates the MCP declaration under `tools/` and legacy connectors.\n" +
		"import { collectConnectors } from \"managed-deepagents/runtime\";\n" +
		"import * as _connector0 from \"./tools/mcp\";\n\n" +
		"export const connectors = collectConnectors([\n" +
		"  { source: \"tools/mcp.ts\", module: { connector: _connector0.mcp } },\n]);\n"
	if got := f.read(t, "_mda_connectors.ts"); got != want {
		t.Fatalf("_mda_connectors.ts:\n%s", got)
	}
	// The connectors module is carried over verbatim.
	if got := f.read(t, "tools/mcp.ts"); got != tsMcp {
		t.Fatalf("tools/mcp.ts: %q", got)
	}
	// The built-in MCP adapter rides along in the managed stack.
	dependencies := readJSON(t, f.read(t, "package.json"))["dependencies"].(map[string]any)
	if dependencies["@langchain/mcp-adapters"] != managedMcpAdapterVersion(t) {
		t.Fatalf("dependencies: %v", dependencies)
	}
}

func TestCompileWiresPythonToolsMcp(t *testing.T) {
	f := pythonProject(t, map[string]string{
		"agent.py":       pyAgent,
		"tools/mcp.py":   pyMcp,
		"pyproject.toml": "[project]\nname = \"example\"\nversion = \"0.0.0\"\ndependencies = [\"deepagents>=0.7.3\"]\n",
	})

	mustCompile(t, f.deploy)

	requireContains(t, f.read(t, "_mda_entry.py"), "from _mda_connectors import connectors as _connectors",
		"await compile_managed_agent_async(_definition, config, context_repo=_context_repo, has_skills=_has_skills, "+
			"connectors=_connectors, async_subagent_graphs=_async_subagent_graphs, runtime=runtime)")
	want := "# Generated by `mda deploy` — do not edit.\n#\n" +
		"# Collects and validates the MCP declaration under `tools/` and legacy connectors.\n" +
		"from types import SimpleNamespace\n" +
		"from managed_deepagents.runtime import collect_connectors\n" +
		"import tools.mcp as _connector0\n\n" +
		"connectors = collect_connectors([\n" +
		"    (\"tools/mcp.py\", SimpleNamespace(connector=_connector0.mcp)),\n])\n"
	if got := f.read(t, "_mda_connectors.py"); got != want {
		t.Fatalf("_mda_connectors.py:\n%s", got)
	}
	pyproject := f.read(t, "pyproject.toml")
	requireContains(t, pyproject, "fastmcp>=4.0.10,<5", "langchain[mcp]>=1.4.6,<2", "\"mcp>=2.2.0,<3\"")
	requireNotContains(t, pyproject, "langchain-mcp-adapters")
	if !f.exists("__runtime__/managed_deepagents/_connectors.py") {
		t.Fatal("the runtime was not vendored")
	}
}

