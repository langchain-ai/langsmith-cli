func TestCompileWiresTypescriptIdentity(t *testing.T) {
	f := typescriptProject(t, map[string]string{"agent.ts": tsAgent, "identity.ts": tsIdentity})

	summary := mustCompile(t, f.local)

	// The entry imports the identity declaration and passes it to the runtime.
	requireContains(t, f.read(t, "_mda_entry.ts"), "import { identity } from \"./identity\";",
		"compileManagedAgent(definition, config, { contextRoot, hasSkills, identity, asyncSubagentGraphs }, runtime)")
	requireContains(t, f.read(t, "_mda_auth.ts"), "export const auth = buildManagedAuth(identity);")
	requireContains(t, f.read(t, "_mda_http.ts"), "export const app = buildManagedHttpApp({ identity });")
	manifest := readJSON(t, f.read(t, "langgraph.json"))
	auth := manifest["auth"].(map[string]any)
	http := manifest["http"].(map[string]any)
	// Local builds turn off the Studio auth scheme: the dev server grants that
	// identity on the `x-auth-scheme` header alone, with no credential check.
	if auth["path"] != "./_mda_auth.ts:auth" || auth["disable_studio_auth"] != true ||
		http["app"] != "./_mda_http.ts:app" || http["middleware_order"] != "middleware_first" {
		t.Fatalf("langgraph.json: %v", manifest)
	}
	if summary.Identity == nil || summary.Identity.Path != "identity.ts" {
		t.Fatalf("identity: %+v", summary.Identity)
	}
	// The identity module is carried over verbatim.
	if got := f.read(t, "identity.ts"); got != tsIdentity {
		t.Fatalf("identity.ts: %q", got)
	}
}

